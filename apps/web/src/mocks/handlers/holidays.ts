export const mockHolidays: Array<{ holidayDate: string; name: string; source: string; isDayOff: boolean }> = []

function parseGovernmentHolidayCSV(year: number) {
  const [, ...rows] = governmentHolidayCSV.split(/\r?\n/)
  return rows.flatMap((row) => {
    const [date, rowYear, name = '', , , description = ''] = row.split(',')
    if (Number(rowYear) !== year || !/^\d{8}$/.test(date)) return []
    return [{
      holidayDate: `${date.slice(0, 4)}-${date.slice(4, 6)}-${date.slice(6, 8)}`,
      name: name || description,
      source: 'gov_calendar',
      isDayOff: row.split(',')[3] === '是'
    }]
  })
}

export const holidaysHandlers = [
  http.get('/api/v1/holidays', ({ request }) => {
    const url = new URL(request.url)
    const start = url.searchParams.get('startDate') || ''
    const end = url.searchParams.get('endDate') || '9999-12-31'
    return HttpResponse.json({ data: mockHolidays.filter((item) => item.holidayDate >= start && item.holidayDate <= end) })
  }),
  http.post('/api/v1/holidays', async ({ request }) => {
    const body = await request.json() as any
    const item = { holidayDate: body.holidayDate, name: body.name, source: 'manual', isDayOff: body.isDayOff !== false }
    const existingIndex = mockHolidays.findIndex((holiday) => holiday.holidayDate === item.holidayDate)
    if (existingIndex >= 0) mockHolidays[existingIndex] = item
    else mockHolidays.push(item)
    return HttpResponse.json({ data: item })
  }),
  http.post('/api/v1/holidays/import', async ({ request }) => {
    const body = await request.json() as { year?: number }
    const year = Number.isInteger(body.year) ? body.year! : new Date().getFullYear()
    const imported = parseGovernmentHolidayCSV(year)
    for (const item of imported) {
      const existingIndex = mockHolidays.findIndex((holiday) => holiday.holidayDate === item.holidayDate)
      if (existingIndex >= 0) {
        if (mockHolidays[existingIndex].source !== 'manual') mockHolidays[existingIndex] = item
      } else {
        mockHolidays.push(item)
      }
    }
    const importedCount = imported.length
    return HttpResponse.json({ data: { importedCount, year } })
  }),
  http.delete('/api/v1/holidays/:date', ({ params }) => {
    const index = mockHolidays.findIndex((item) => item.holidayDate === params.date)
    if (index >= 0) mockHolidays.splice(index, 1)
    return HttpResponse.json({ data: { deleted: true } })
  })
]
